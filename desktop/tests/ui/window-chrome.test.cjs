const assert = require('node:assert/strict');
const { test } = require('node:test');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
test('frameless shell keeps native transport hooks and owns frontend controls', () => {
  const read = file => fs.readFileSync(path.join(root, file), 'utf8');
  const windowConfig = JSON.parse(read('src-tauri/tauri.conf.json')).app.windows[0];
  assert.equal(windowConfig.decorations, false);
  assert.equal(windowConfig.minWidth, 520);
  assert.equal(windowConfig.minHeight, 420);
  const chrome = read('src-tauri/src/desktop_chrome.rs');
  assert.match(chrome, /authorize\(&window\)\?/);
  assert.match(chrome, /async fn window_action\(/, 'window IPC must not synchronously block the WebView message loop');
  assert.match(chrome, /WindowAction::Close => window.close\(\)/);
  assert.match(chrome, /js_init_script/);
  assert.match(chrome, /async fn sync_surface\(/);
  assert.match(chrome, /set_background_color/);
  assert.match(chrome, /ScaleFactorChanged/);
  assert.match(chrome, /NotifyParentWindowPositionChanged/);
  assert.doesNotMatch(chrome, /MoveFocus|set_focus\(/, 'position updates must not reset composition');
  const lib = read('src-tauri/src/lib.rs');
  assert.doesNotMatch(lib, /uninstall::setup_menu|uninstall::on_menu_event/);
  assert.match(lib, /downloads::setup\(app\)/);
  assert.match(lib, /register_uri_scheme_protocol\("neo-start"/);
  assert.doesNotMatch(lib, /start_url:/, 'launcher cannot be learned from a loaded error page');
  const launcherNavigation = read('src-tauri/src/uninstall.rs').split('pub fn return_start_page')[1].split('#[cfg(test)]')[0];
  assert.match(launcherNavigation, /bootstrap_page::url\(\)/);
  assert.doesNotMatch(launcherNavigation, /stop_existing_child|app.exit/);
  const bootstrap = lib.split('fn bootstrap_state')[1].split('#[tauri::command]')[0];
  assert.doesNotMatch(bootstrap, /ensure_owner\(/, 'read-only launcher status does not take runtime ownership');
  assert.match(lib, /on_window_event\(tray::on_window_event\)/);
  const ui = read('ui/window-chrome.js');
  for(const action of ['minimize','toggle_maximize','close','start_page','check_updates','uninstall']) assert.ok(ui.includes(action));
  assert.match(ui, /attachShadow/);
  assert.match(ui, /aria-label="应用菜单"/);
  assert.match(ui, /event.key === 'Escape'/);
  assert.doesNotMatch(ui, /·/);
});
